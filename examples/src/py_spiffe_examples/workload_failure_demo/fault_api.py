"""Scripted Workload API behaviour with py-spiffe's real retry state machine.

The loop below mirrors ``WorkloadApiClient._watch_x509_context_updates``:
updates reset the retry counter, classified-permanent gRPC codes stop the
watcher, everything else backs off and retries. Backoff numbers and retry
eligibility come from the library itself (``RetryHandler``/``RetryPolicy``),
so the timeline cannot drift from production behaviour.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import grpc

from spiffe.workloadapi.workload_api_client import RetryHandler, RetryPolicy


@dataclass(frozen=True)
class Message:
    """One Workload API response, already parsed by py-spiffe."""

    label: str
    not_after: float | None = None
    federated_domains: tuple[str, ...] = ()
    svid_serial: int | None = None


@dataclass(frozen=True)
class Event:
    """A scripted server behaviour at virtual second ``at``."""

    at: float
    kind: str  # update | error | drop | silent
    code: grpc.StatusCode = grpc.StatusCode.UNAVAILABLE
    message: Message | None = None


@dataclass
class Attempt:
    at: float
    outcome: str
    code: str | None = None
    backoff: float | None = None


@dataclass
class Timeline:
    policy: RetryPolicy
    events: list[Event]
    attempts: list[Attempt] = field(default_factory=list)
    updates: list[tuple[float, Message]] = field(default_factory=list)
    stopped_at: float | None = None
    stop_reason: str | None = None


def simulate(
    events: list[Event],
    *,
    policy: RetryPolicy | None = None,
    retry_connect: bool = True,
    horizon: float | None = None,
) -> Timeline:
    """Runs the watcher deterministically over virtual time."""
    policy = policy or RetryPolicy()
    timeline = Timeline(policy=policy, events=sorted(events, key=lambda e: e.at))
    retry = RetryHandler(policy) if retry_connect else None
    now = 0.0
    pending_backoff: float | None = None

    for event in timeline.events:
        if horizon is not None and event.at > horizon:
            break
        # A retry fires only once its backoff has elapsed; a server event that
        # arrives earlier is observed by the next attempt at the scheduled time.
        if pending_backoff is not None:
            retry_fire_at = now + pending_backoff
            if event.at < retry_fire_at:
                # The server event happens while this client is still backing
                # off; the retry attempt itself occurs first.
                timeline.attempts.append(Attempt(retry_fire_at, 'retry attempt'))
                now = retry_fire_at
            pending_backoff = None
        now = max(now, event.at)

        if event.kind == "silent":
            timeline.attempts.append(Attempt(now, "stream open (no data)"))
            continue

        if event.kind == "drop":
            timeline.attempts.append(Attempt(now, "stream ended"))
            if retry is None or not retry.can_retry():
                timeline.stopped_at = now
                timeline.stop_reason = "stream ended (fail-closed)"
                return timeline
            backoff = retry.get_backoff()
            timeline.attempts[-1].backoff = backoff
            pending_backoff = backoff
            continue

        if event.kind == "error":
            timeline.attempts.append(Attempt(now, "error", event.code.name))
            if retry is None or not retry.should_retry(event.code):
                timeline.stopped_at = now
                timeline.stop_reason = f"{event.code.name} is non-retryable"
                return timeline
            backoff = retry.get_backoff()
            timeline.attempts[-1].backoff = backoff
            pending_backoff = backoff
            continue

        if event.kind == "update":
            assert event.message is not None
            timeline.attempts.append(Attempt(now, "update delivered"))
            timeline.updates.append((now, event.message))
            if retry is not None:
                retry.reset()
            continue

        raise ValueError(f"unknown event kind {event.kind!r}")

    return timeline


def schedule(policy: RetryPolicy, retries: int) -> list[float]:
    """Backoff sequence generated by the library's RetryHandler."""
    handler = RetryHandler(policy)
    return [handler.get_backoff() for _ in range(retries)]
